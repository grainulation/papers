#!/usr/bin/env python3
"""Render RESULTS.md from results/*.json produced by collect_v3.py / evaluate_v3.py.
Every number in RESULTS.md is read from those files; nothing is typed by hand."""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"
ev = json.load(open(R / "evaluation_v3.json"))
prov = json.load(open(R / "build_provenance.json"))
man = json.load(open(R / "run_manifest.json")) if (R / "run_manifest.json").exists() else None
man2p = HERE / "results_rep2" / "run_manifest.json"
man2 = json.load(open(man2p)) if man2p.exists() else None

L = []
P = L.append

LABELS = {
    "rust": "Rust reducer (actual binary, default policy)",
    "rust_rec0": "Rust, recency weight 0 (Schulze still sees rec dim)",
    "rust_nodb": "Rust, deadband off (no Schulze)",
    "rust_rec0nodb": "Rust, recency weight 0 + deadband off",
    "rust_evonly": "Rust evidence-only (argmax Rust ev)",
    "python_bran": "Python v2 reducer (recency = file order)",
    "python_bran_listorder": "Python v2 reducer, recency = agent LIST order",
    "python_bran_on_slot": "Python v2 reducer on the Rust slot",
    "python_no_recency": "Python v2 reducer, recency off",
    "evidence_only_py": "Python evidence-only",
    "majority": "Majority vote",
    "first_member": "First member (earliest arrival)",
    "last_member": "Last member (latest arrival)",
}
DSNAMES = {"v3": "v3 re-collected responses, seq = recorded arrival order",
           "v3rep2": "v3 replicate 2 (request seed 43), seq = recorded arrival order",
           "v3pool": "v3 + replicate 2 pooled (clustered by question)",
           "v1orig": "ORIGINAL v1 responses through the Rust reducer, seq = agent LIST order (no arrival times exist)"}


def p(x):
    return "—" if x is None else (f"{x:.4g}" if isinstance(x, float) else str(x))


P("# Eval v3 results\n")
P("Generated by `make_results.py` from `results/evaluation_v3.json`, `results/run_manifest.json`, "
  "`results/build_provenance.json`. Do not edit by hand.\n")

P("## Provenance\n")
P(f"- Rust binary sha256: `{ev['binary_sha256']}` ({prov['rustc']}); built from git HEAD `{prov['git_head']}` "
  f"plus uncommitted edits, per-file source hashes in `results/build_provenance.json`.")
for ds, d in ev["datasets"].items():
    P(f"- `{ds}` native policy hash reported by the binary: `{d.get('native_policy_hash')}`")
if man:
    P(f"- Ollama {man['ollama_version'].get('version')}; options {json.dumps(man['options'])}; "
      f"dispatch seed {man['dispatch_seed']}; timeout {man['timeout_s']} s.")
    P(f"- Server config (startup log): {json.dumps(prov['ollama_server_log_config'])}.")
    P("- Model digests:\n")
    P("| model | digest | quant | params |\n|---|---|---|---|")
    for m, x in man["model_digests"].items():
        P(f"| {m} | `{x['digest']}` | {x['quantization']} | {x['parameter_size']} |")
    P("")
rep2_raw = sorted((HERE / "results_rep2" / "raw").glob("q*.json"))
P(f"- **`results_rep2/` is INCOMPLETE and unused**: a second replicate (request seed 43, dispatch seed "
  f"20261022) was stopped on request after {len(rep2_raw)} of 55 questions. It is kept on disk, but no table "
  f"uses it.\n")

for key, title in [("arrival", "v3"), ("arrival_rep2", "v3 replicate 2")]:
    a = ev.get(key) or {}
    if not a:
        continue
    P(f"## Arrival order ({title})\n")
    P(f"- Questions: {a['questions']}; request errors: {a['errors']}.")
    P(f"- Arrival order identical to agent list order: **{a['arrival_equals_list_order']} / {a['questions']}** questions.")
    P(f"- Mean Kendall tau(arrival, list order): {a['mean_kendall_tau_vs_list']}.")
    P(f"- Latest arrival per question: {json.dumps(a['last_arrival_counts'])} "
      f"(list-last agent qwen2.5_3b was last in {a['last_arrival_is_qwen(list-last)']}).")
    P(f"- Mean arrival rank (0 = first): {json.dumps(a['mean_arrival_rank_by_agent'])}.")
    P(f"- Max requests in flight per question: {json.dumps(a['max_in_flight_requests_per_question'])}; "
      f"max models resident in `/api/ps` samples: {a['max_models_resident_seen_in_api_ps']}.")
    P(f"- Per-question detail: `results/arrival_order{'' if key == 'arrival' else '_results_rep2'}.csv`.\n")

for ds, d in ev["datasets"].items():
    P(f"## Dataset `{ds}`: {DSNAMES.get(ds, ds)}\n")
    P(f"Runs (question × replicate): {d['questions']}; contributions: {d['contributions']}.\n")
    mv = d["mirror_validation"]
    P("### Python ↔ Rust equivalence\n")
    P(f"- Python mirror of compiler.rs P4/P5 vs the binary (winner, quantized scores, deadband flag, "
      f"admitted set): native policy {mv['native']['questions_mismatched']} / {mv['native']['questions']} "
      f"runs mismatched; forced policy {mv['forced']['questions_mismatched']} / {mv['forced']['questions']}.")
    P(f"- Mirror step L0 vs `evaluate_v2.bran_idx`: {d['mirror_L0_vs_evaluate_v2_mismatches']} mismatches.")
    e = d["equivalence"]
    P(f"- Python v2 reducer vs Rust (native policy), per Python conflict set, agreement = same output "
      f"object(s): **{e['agree']} / {e['python_sets']}** "
      f"(contradiction sets {e['contradiction_agree']} / {e['contradiction_sets']}; "
      f"singleton/redundancy sets {e['redundancy_agree']} / {e['redundancy_sets']}). "
      f"Ladder end-state equals Rust in {e['ladder_final_equals_rust']} / {e['python_sets']}.\n")
    P("| set type | primary cause of disagreement | sets |\n|---|---|---|")
    for k, n in e["by_type_and_cause"].items():
        t, c = k.split("|")
        P(f"| {t} | {c} | {n} |")
    P("")
    for gname, glabel in [("v1", "original grader"), ("v2", "stricter grader")]:
        for tname, tlabel in [("A_python_slots", "A: Python-harness slots (Rust with forced exclusive-value policy)"),
                              ("B_rust_native_slots", "B: Rust-native slots (default policy)")]:
            t = d["tables"].get(f"{tname}|{gname}")
            if not t:
                continue
            P(f"### {tlabel}, {glabel}\n")
            P(f"Eligible {t['eligible']} (from {t['eligible_questions']} questions), decisive "
              f"{t['decisive']} (from {t['decisive_questions']} questions). Rust top-2 gap < 0.05 "
              f"(deadband → Schulze): {t['rust_in_deadband']['eligible']} eligible, "
              f"{t['rust_in_deadband']['decisive']} decisive; of the deadband winners, the latest-arriving "
              f"candidate won {t['deadband_winner_is_latest_candidate']['latest']} / "
              f"{t['deadband_winner_is_latest_candidate']['eligible_in_deadband']} "
              f"({t['deadband_winner_is_latest_candidate']['decisive_latest']} / "
              f"{t['deadband_winner_is_latest_candidate']['decisive_in_deadband']} decisive).")
            mf = t.get("majority_same_correctness_as_first_member")
            if mf:
                P(f" Majority vote has the same correctness as first-member on {mf['eligible']} / {t['eligible']} "
                  f"eligible and {mf['decisive']} / {t['decisive']} decisive sets (distinct object strings rarely "
                  f"repeat, so majority usually falls back to the first-seen object).")
            if "rust_outcome_counts" in t:
                P(f" Rust outcome on these sets: {json.dumps(t['rust_outcome_counts'])} "
                  f"(decisive: {json.dumps(t['rust_outcome_counts_decisive'])}); 'dissolved' = Rust forms no "
                  f"contradiction slot (LOW members excluded), scored correct iff every admitted member matches gold.")
            P("")
            P("| method | eligible correct | decisive correct | vs majority b/c | exact McNemar p |\n|---|---|---|---|---|")
            for m, a in t["accuracy"].items():
                vm = t["vs_majority"].get(m, {})
                bc = f"{vm['b']}/{vm['c']}" if vm else "—"
                P(f"| {LABELS.get(m, m)} | {a['eligible_correct']}/{t['eligible']} | "
                  f"{a['decisive_correct']}/{t['decisive']} | {bc} | {p(vm.get('p_exact'))} |")
            bs = t.get("bootstrap_rust_minus_majority")
            if bs:
                line = (f"\nQuestion-clustered bootstrap, Rust − majority ({bs['resamples']} resamples, seed {bs['seed']}, "
                        f"{bs['n_questions']} questions): all eligible {bs['diff']:.4f}, 95% CI "
                        f"[{bs['ci95'][0]:.4f}, {bs['ci95'][1]:.4f}]")
                bd = t.get("bootstrap_rust_minus_majority_decisive")
                P(line + ("" if bd else "."))
                if bd:
                    L[-1] += (f"; decisive only {bd['diff']:.4f}, 95% CI [{bd['ci95'][0]:.4f}, {bd['ci95'][1]:.4f}] "
                      f"({bd['n_questions']} questions).")
            mg = t["margins"]
            P(f"\nSeparation over decisive sets with Rust scores ({mg['with_rust_scores']} of {mg['decisive_rows']}; "
              f"{json.dumps(mg['status_counts'])}): evidence gap > 0.05 in **{mg['ev_separated']['separated']}** "
              f"(correct {mg['ev_separated']['sep_correct']}, wrong {mg['ev_separated']['sep_wrong']}); "
              f"total-score gap > 0.05 in **{mg['score_separated']['separated']}** "
              f"(correct {mg['score_separated']['sep_correct']}, wrong {mg['score_separated']['sep_wrong']}); "
              f"evidence gap > 0 in {mg['ev_gap_positive']}; Rust deadband flag set in {mg['in_deadband']}. "
              f"Unseparated: correct {mg['score_separated']['nosep_correct']}, wrong {mg['score_separated']['nosep_wrong']}.")
            P(f"\nDecisive-set members correct by agent [correct, total]: "
              f"{json.dumps(t['decisive_member_correct_by_agent'])}; agent of the earliest-arriving member: "
              f"{json.dumps(t['decisive_first_member_agent'])}.")
            P(f"\nDecisive conflicts per question: {json.dumps(t['decisive_per_question'])}\n")
            P(f"Files: `results/paired_decisions_{ds}_{tname}_{gname}.csv`, "
              f"`results/separation_margins_{ds}_{tname}_{gname}.csv`.\n")
    ps = d.get("precision_sheet_rows")
    if ps:
        P(f"### Precision adjudication sheet\n\n`results/precision_adjudication_{ds}.csv`: "
          f"{ps['rows_failing_v2']} of {ps['admitted_total']} Rust-admitted contributions fail the stricter "
          f"grader. HEURISTIC (not adjudicated) categories: {json.dumps(ps['heuristic_distribution'])}. "
          f"`human_label` is empty by design.\n")

P("## Decisive-conflict yield and how to raise it honestly\n")
P("| dataset | table | grader | eligible | decisive | questions with ≥1 decisive set |\n|---|---|---|---|---|---|")
for ds, d in ev["datasets"].items():
    for k, t in d["tables"].items():
        tn, g = k.split("|")
        P(f"| {ds} | {tn} | {g} | {t['eligible']} | {t['decisive']} | {t['decisive_questions']} / 55 |")
P("""
Few questions produce a decisive conflict. Most contradiction sets are free-text objects under
`is`/`has`, and the extracted objects rarely repeat verbatim, so majority vote almost always
falls back to the first-seen object. No increase is made here. A second sampling replicate of the same 55 questions
with the existing gold was started, then stopped incomplete, and is unused. Finishing it is the
cheapest honest increase. Further increases need new author-written gold, and are suggestions only:

1. **Single-valued questions with known small-model confusions.** These are numeric or entity
   answers, for example dates, counts, units, capitals and authorship, where 3B-class models
   disagree. Each needs one gold triple on a FUNCTIONAL predicate.
2. **A constrained answer line in the prompt**, e.g. `ANSWER: <entity>`, lowered to one
   functional triple per agent. Every question then yields one comparable slot. This is a new
   protocol and must be reported as such.
3. **Object canonicalization before slotting**: strip markdown, normalize units and numbers.
   This removes formatting-only "conflicts" and merges true agreements, so majority stops
   degenerating to first-member.
4. **Declared `incompatible_values` for each question's answer alternatives.** Without this,
   non-functional predicates never conflict in the Rust reducer.
5. **More samples per model, or a larger and more diverse model pool.** Pool them with the
   question-clustered bootstrap (`evaluate_v3.py` has `v3rep2`/`v3pool` dataset hooks for this).
""")

P("""## Caveats

- **Grader.** Both graders are unvalidated, and gold is one author's triples. The precision
  sheet's `human_label` column is empty.
- **Small sample.** The decisive counts are small. Every McNemar p and bootstrap CI here is
  underpowered. Read the p-values with that in mind; v1orig results inherit the list-order recency of the original harness.
- **Unexercised Rust machinery.** The identity lowering emits no NEGATE polarity and no
  critiques, so Rust polarity handling and critique survival are not exercised. Their
  equivalence-cause counts are 0 by construction, not by measurement. The same holds for
  calibration, which is 0.7 for every agent on both sides.
- **Evidence sources.** An evidence `source` is the item's text, so the cross-reference
  multiplier fires only on identical text. The placeholder text `context-associated`, written by
  `evaluate_v1.enrich_evidence_from_context`, is identical across agents. It therefore earns the
  ≥2/≥3-citer bonus, a harness artifact inherited from the shared extraction.
- **Recency-off does not remove recency from Schulze.** Setting the recency weight to 0 leaves
  recency as one of Schulze's five unweighted dimensions. Only "recency 0 + deadband off"
  removes recency entirely.
- **What arrival order measures.** It reflects model speed, load state and server queueing
  (`OLLAMA_NUM_PARALLEL=1`, at most 3 resident models). It is a model-identity proxy, not a
  correctness signal. The evaluator was occasionally run during collection, which added minor
  CPU contention.
- **Request seed.** v3 requests set `seed` (42); the original collection set none. The two
  datasets therefore differ in sampling as well as in recency source.
- **Python harness view.** `v1orig` recency uses agent list order. `collect.py` queried the
  models one at a time in that order, so list order equals the original completion order, but
  no timestamps were recorded.
""")

(HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
print(f"wrote {HERE / 'RESULTS.md'} ({len(L)} lines)")
