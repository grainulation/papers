#!/usr/bin/env python3
"""Render RESULTS.md from results/evaluation_canon.json (+ CSVs, test log) produced by
run_canon.py / test_canon.py. Every number is read from those files."""

import csv
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"
ev = json.load(open(R / "evaluation_canon.json"))
v3ref = json.load(open(HERE.parent.parent / "v3" / "results" / "evaluation_v3.json"))
seal = ev["seal"]
L = []
P = L.append

LABELS = {
    "rust": "Rust reducer (default policy)",
    "rust_rec0": "Rust, recency weight 0",
    "rust_nodb": "Rust, deadband off",
    "rust_rec0nodb": "Rust, recency 0 + deadband off",
    "rust_evonly": "Rust evidence-only",
    "python_bran": "Python v2 reducer (file order)",
    "python_bran_listorder": "Python v2 reducer, LIST order",
    "python_bran_on_slot": "Python v2 reducer on the Rust slot",
    "python_no_recency": "Python v2 reducer, recency off",
    "evidence_only_py": "Python evidence-only",
    "majority": "Majority vote",
    "first_member": "First member",
    "last_member": "Last member",
}
MAIN = ["rust", "rust_rec0nodb", "rust_evonly", "majority", "first_member", "last_member"]
DS = {"v3": "v3 re-collected responses (seq = recorded arrival order)",
      "v1orig": "original v1 responses (seq = agent list order)"}
TN = {"A_python_slots": "A: Python-harness slots (Rust forced exclusive-value policy)",
      "B_rust_native_slots": "B: Rust-native slots (default policy)"}
GN = {"v1": "original grader", "v2": "stricter grader"}


def f(x, n=4):
    return f"{x:.{n}g}" if isinstance(x, float) else str(x)


def rows(path):
    with open(path) as fh:
        return list(csv.DictReader(fh))


P("# L10: object canonicalization for a fair majority baseline — results\n")
P("Generated by `make_results.py` from `results/evaluation_canon.json`, `results/*.csv` and "
  "`results/test_canon.txt`. Do not edit by hand.\n")

P("## Seal\n")
P(f"- Canonicalizer: `{seal['canon_version']}`, `canon.py` sha256 `{seal['canon_py_sha256']}`.")
P(f"- `run_canon.py` sha256 `{seal['run_canon_py_sha256']}`; imported `v3/evaluate_v3.py` sha256 "
  f"`{seal['evaluate_v3_py_sha256']}` (unmodified).")
P(f"- Rust binary `{Path(seal['binary']).name}` sha256 `{seal['binary_sha256']}` (the v3 binary; same "
  f"`--reduce` path as `evaluate_v3.py`).")
P(f"- Bootstrap {seal['bootstrap']} resamples, seed {seal['seed']}, clustered by question.")
for ds in ev["modes"].get("canon", {}):
    P(f"- `{ds}` native policy hash: raw `{ev['modes']['raw'][ds]['native_policy_hash']}`, canon "
      f"`{ev['modes']['canon'][ds]['native_policy_hash']}` (differs only because the three "
      f"`incompatible_values` fixture strings are canonicalized too).")
tlog = (R / "test_canon.txt").read_text() if (R / "test_canon.txt").exists() else ""
m = re.search(r"Ran (\d+) tests?", tlog)
P(f"- Unit tests (`python3 -m unittest test_canon`): {m.group(1) if m else '?'} tests, "
  f"{'OK' if tlog.rstrip().endswith('OK') else 'NOT OK'} (`results/test_canon.txt`).")
P("- Synonym table (complete):\n")
P("| token | rewritten to | observed in |\n|---|---|---|")
for k, v in seal["synonyms"].items():
    P(f"| `{k}` | `{v['to']}` | {v['source']} |")
P("")

P("## Reproduction check\n")
for ds in ev["modes"]["raw"]:
    same = ev["modes"]["raw"][ds] == {**v3ref["datasets"][ds]}
    P(f"- `raw` mode (no canonicalization) vs `v3/results/evaluation_v3.json`, dataset `{ds}`: "
      f"{'**identical**' if same else '**DIFFERS**'} (every summary statistic).")
P("")

P("## How canonicalization changes the Python conflict sets\n")
P("Same contributions, same (subject, predicate) groups; only the object comparison changes. "
  "'Real majority' = the most frequent object occurs more than once. Per-set detail: "
  "`results/conflict_sets_raw_vs_canon_<ds>.csv`; every merge: `results/merge_audit_<ds>.csv`; "
  "every object raw → canonical: `results/canon_map_<ds>.csv`.\n")
P("| | v3 | v1orig |\n|---|---|---|")
S = ev["structure"]
dss = [d for d in ["v3", "v1orig"] if d in S]


def row(label, fn):
    P(f"| {label} | " + " | ".join(str(fn(S[d])) for d in dss) + " |")


cm = {d: rows(R / f"canon_map_{d}.csv") for d in dss}
P("| contributions | " + " | ".join(str(len(cm[d])) for d in dss) + " |")
P("| contributions whose canonical object ≠ Rust `normalize_object` | " +
  " | ".join(str(sum(int(r["changed_vs_rust_normalize"]) for r in cm[d])) for d in dss) + " |")
row("contradiction sets (raw objects)", lambda s: s["raw_contradiction_sets"])
row("… dissolved (all members canonically equal = formatting-only)", lambda s: s["dissolved_formatting_only"])
row("… remaining contradiction sets", lambda s: s["canon_contradiction_sets"])
row("… sets with fewer distinct objects after canon", lambda s: s["sets_with_fewer_distinct_objects"])
row("sets with a real majority, raw", lambda s: s["real_majority_raw"])
row("remaining sets with a real majority, canon", lambda s: s["real_majority_canon_surviving_sets"])
row("strict plurality (unique top, count > 1), raw / canon-remaining",
    lambda s: f"{s['strict_plurality_raw']} / {s['strict_plurality_canon_surviving_sets']}")
row("majority winner's object ≠ first member's object, raw / canon-remaining",
    lambda s: f"{s['majority_winner_not_first_raw']} / {s['majority_winner_not_first_canon_surviving']}")
row("canonical classes merging > 1 distinct raw string", lambda s: s["merge_classes"])
row("… of which members get different grades, original / stricter grader",
    lambda s: f"{s['merge_classes_mixed_correctness']['v1']} / {s['merge_classes_mixed_correctness']['v2']}")
for g in ["v1", "v2"]:
    row(f"{GN[g]}: eligible raw sets dissolved / eligible", lambda s, g=g: f"{s['grader_' + g]['eligible_dissolved']} / {s['grader_' + g]['raw_eligible']}")
    row(f"{GN[g]}: decisive raw sets dissolved / decisive", lambda s, g=g: f"{s['grader_' + g]['decisive_dissolved']} / {s['grader_' + g]['raw_decisive']}")
    row(f"{GN[g]}: decisive remaining sets with a real majority, raw → canon",
        lambda s, g=g: f"{s['grader_' + g]['decisive_surviving_real_majority_raw']} → {s['grader_' + g]['decisive_surviving_real_majority_canon']}")
P("")
P("### Every merge (canonical classes with > 1 distinct raw string)\n")
P("Member grades are in member order (1 = matches gold). Graders always see the RAW object.\n")
P("| dataset | question | (subject, predicate) | canonical | raw variants | n | orig. grader | stricter |")
P("|---|---|---|---|---|---|---|---|")
for d in dss:
    for r in rows(R / f"merge_audit_{d}.csv"):
        P(f"| {d} | {r['question']} | ({r['subject']}, {r['predicate']}) | `{r['canonical_object']}` | "
          f"{r['raw_variants'].replace('|', '/').replace('*', '\\*')} | {r['n_members']} | "
          f"{r['grader_v1_member_correct']} | {r['grader_v2_member_correct']} |")
P("")

for ds in dss:
    P(f"## Dataset `{ds}`: {DS[ds]}\n")
    c = ev["modes"]["canon"][ds]
    mv = c["mirror_validation"]
    eq = c["equivalence"]
    P(f"- Canon mode, Python mirror vs binary: native {mv['native']['questions_mismatched']} / "
      f"{mv['native']['questions']} runs mismatched, forced {mv['forced']['questions_mismatched']} / "
      f"{mv['forced']['questions']}; mirror L0 vs `evaluate_v2.bran_idx`: {c['mirror_L0_vs_evaluate_v2_mismatches']} mismatches.")
    r0 = ev["modes"]["raw"][ds]["equivalence"]
    P(f"- Python v2 reducer vs Rust native, per Python set: raw {r0['agree']} / {r0['python_sets']}, "
      f"canon {eq['agree']} / {eq['python_sets']} (contradiction sets raw {r0['contradiction_agree']} / "
      f"{r0['contradiction_sets']}, canon {eq['contradiction_agree']} / {eq['contradiction_sets']}).\n")
    for g in ["v1", "v2"]:
        for t in ["A_python_slots", "B_rust_native_slots"]:
            k = f"{t}|{g}"
            a, b = ev["modes"]["raw"][ds]["tables"][k], c["tables"][k]
            P(f"### {TN[t]}, {GN[g]}\n")
            P(f"Eligible {a['eligible']} → **{b['eligible']}**, decisive {a['decisive']} → **{b['decisive']}** "
              f"(questions with a decisive set {a['decisive_questions']} → {b['decisive_questions']}). "
              f"Majority has the same correctness as first-member on {a['majority_same_correctness_as_first_member']['eligible']}/{a['eligible']} → "
              f"{b['majority_same_correctness_as_first_member']['eligible']}/{b['eligible']} eligible and "
              f"{a['majority_same_correctness_as_first_member']['decisive']}/{a['decisive']} → "
              f"{b['majority_same_correctness_as_first_member']['decisive']}/{b['decisive']} decisive sets. "
              f"Rust in deadband: {b['rust_in_deadband']['eligible']} eligible / {b['rust_in_deadband']['decisive']} decisive (canon).\n")
            P("| method | raw: eligible · decisive | raw vs maj. b/c, p | **canon: eligible · decisive** | canon vs maj. b/c, p |")
            P("|---|---|---|---|---|")
            for meth in MAIN:
                if meth not in b["accuracy"]:
                    continue
                cells = []
                for s in (a, b):
                    acc = s["accuracy"][meth]
                    vm = s["vs_majority"].get(meth)
                    cells.append(f"{acc['eligible_correct']}/{s['eligible']} · {acc['decisive_correct']}/{s['decisive']}")
                    cells.append("—" if vm is None else f"{vm['b']}/{vm['c']}, {f(vm['p_exact'])}")
                P(f"| {LABELS[meth]} | {cells[0]} | {cells[1]} | **{cells[2]}** | {cells[3]} |")
            for nm, s in (("raw", a), ("canon", b)):
                bs = s.get("bootstrap_rust_minus_majority")
                bd = s.get("bootstrap_rust_minus_majority_decisive")
                if bs:
                    P(f"\nBootstrap Rust − majority, {nm}: eligible {f(bs['diff'])} [{f(bs['ci95'][0])}, {f(bs['ci95'][1])}] "
                      f"({bs['n_questions']} questions)" + (f"; decisive {f(bd['diff'])} [{f(bd['ci95'][0])}, {f(bd['ci95'][1])}] "
                                                          f"({bd['n_questions']} questions)." if bd else "."))
            P(f"\nAll methods (incl. Python reducers): `results/canon/paired_decisions_{ds}_{t}_{g}.csv`.\n")

P("## Per-set outcome changes (raw → canon)\n")
P("Rows matched by (question, subject, predicate) for Table A and by (question, slot) for Table B, "
  "from `results/{raw,canon}/paired_decisions_*.csv`. A set present only in raw was dissolved by "
  "canonicalization. Listed: every matched set where any method's correctness changed, and every "
  "dissolved set.\n")
P("| dataset | table | grader | set | raw decisive | canon decisive | changes |")
P("|---|---|---|---|---|---|---|")
nchg = 0
for ds in dss:
    for t in ["A_python_slots", "B_rust_native_slots"]:
        for g in ["v1", "v2"]:
            fn = f"paired_decisions_{ds}_{t}_{g}.csv"
            ra, ca = rows(R / "raw" / fn), rows(R / "canon" / fn)
            key = (lambda r: (r["question"], r["subject"], r["predicate"])) if t.startswith("A") else \
                (lambda r: (r["question"], r["slot"]))
            cm_ = {key(r): r for r in ca}
            meths = [m for m in LABELS if m in (ra[0] if ra else {})]
            for r in ra:
                k = key(r)
                lab = " / ".join(k)
                if k not in cm_:
                    P(f"| {ds} | {t[0]} | {g} | {lab} | {r['decisive']} | dissolved | — |")
                    nchg += 1
                    continue
                c2 = cm_[k]
                d = [f"{m} {r[m]}→{c2[m]}" for m in meths if r[m] != c2[m]]
                if d or r["decisive"] != c2["decisive"]:
                    P(f"| {ds} | {t[0]} | {g} | {lab} | {r['decisive']} | {c2['decisive']} | {'; '.join(d) or '—'} |")
                    nchg += 1
            extra = [k for k in cm_ if k not in {key(r) for r in ra}]
            for k in extra:
                P(f"| {ds} | {t[0]} | {g} | {' / '.join(k)} | absent | {cm_[k]['decisive']} | new set |")
P("")

P("## Summary\n")
for ds in dss:
    st = S[ds]
    for g in ["v1", "v2"]:
        a = ev["modes"]["raw"][ds]["tables"][f"A_python_slots|{g}"]
        b = ev["modes"]["canon"][ds]["tables"][f"A_python_slots|{g}"]
        ra, rb = a["accuracy"], b["accuracy"]
        P(f"- `{ds}`, {GN[g]}, Table A: {st['grader_' + g]['eligible_dissolved']} of {a['eligible']} eligible sets "
          f"dissolve as formatting-only, {st['grader_' + g]['decisive_dissolved']} of {a['decisive']} decisive sets do. "
          f"Decisive correct raw → canon: Rust {ra['rust']['decisive_correct']} → {rb['rust']['decisive_correct']}, "
          f"majority {ra['majority']['decisive_correct']} → {rb['majority']['decisive_correct']}, "
          f"first {ra['first_member']['decisive_correct']} → {rb['first_member']['decisive_correct']} (of {b['decisive']}). "
          f"Majority = first-member on {b['majority_same_correctness_as_first_member']['decisive']}/{b['decisive']} decisive sets after canon.")
P("")

P("## Caveats\n")
P("- Canonicalization is applied to OBJECTS only. Subjects are untouched, so sets split by subject "
  "wording (\"glass\" vs \"no, glass\", \"this\", \"it\") stay split; no new conflict sets can appear.")
P("- Graders see the raw object. Where a canonical class merges strings the lexical graders score "
  "differently (see the merge table), majority's correctness depends on which raw member it returns "
  "(the first member of the winning class, as before).")
P("- The rules are conservative by design (tests in `test_canon.py`), so many paraphrases stay "
  "distinct; the result bounds what *formatting-only* canonicalization can do, not semantic clustering.")
P("- Same small-sample caveats as v3: every McNemar p and bootstrap CI here is underpowered.")

(HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
print(f"wrote RESULTS.md ({len(L)} lines)")
